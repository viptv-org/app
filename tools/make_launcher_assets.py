#!/usr/bin/env python3
"""Generate the Android launcher icon and TV banner from design's app-icon master.

The master is design's black and white V (assets/brand/app-icon, generated by
assets/brand/tools/make_app_icon.py at design commit 85179a8; owner decision
2026-10-27, design#21): a white Bricolage Grotesque ExtraBold "V" set at
0.625 x the mark size and centred on its ink box, on #000000. The TV banner is
the white "VIPTV" wordmark on #000000. See androidApp/src/main/LAUNCHER_ASSETS.md.

Requires Pillow and fontTools:
  python3 -m venv /tmp/viptv-icons && /tmp/viptv-icons/bin/pip install pillow==13.0.0 fonttools==4.67.0
  /tmp/viptv-icons/bin/python tools/make_launcher_assets.py
"""
from io import BytesIO
from pathlib import Path

from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "composeApp/src/commonMain/composeResources/font/bricolage.ttf"
RES = ROOT / "androidApp/src/main/res"

BLACK = "#000000"       # design token color.bg-oled
WHITE = "#FFFFFF"       # design token color.fill.white
CORNER = 0.28           # legacy rounded-square corner radius / size
GLYPH_RATIO = 0.625     # "V" font size / mark size
OVERSAMPLE = 8

# Adaptive icons are a 108dp canvas; launchers mask the centre 72dp.
CANVAS_DP, VISIBLE_DP = 108, 72
GENERATED = "<!-- Generated by tools/make_launcher_assets.py; do not edit by hand. -->"
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
LEGACY_DP, LEGACY_INSET_DP = 48, 2
WORDMARK = "VIPTV"


def v_outline():
    """The V glyph as closed polygons in font units (y up), plus its ink box."""
    font = TTFont(FONT)
    glyphs = font.getGlyphSet()
    pen = RecordingPen()
    glyphs[font.getBestCmap()[ord("V")]].draw(pen)
    contours, current = [], []
    for op, args in pen.value:
        if op in ("moveTo", "lineTo"):
            current.append(args[0])
        elif op in ("closePath", "endPath"):
            contours.append(current)
            current = []
        else:  # The Bricolage V is straight-edged; fail loudly if that changes.
            raise SystemExit(f"unexpected curve segment {op} in V glyph")
    points = [p for c in contours for p in c]
    xs, ys = [p[0] for p in points], [p[1] for p in points]
    return contours, (min(xs), min(ys), max(xs), max(ys)), font["head"].unitsPerEm


CONTOURS, (X0, Y0, X1, Y1), UPEM = v_outline()


def place_v(mark, cx, cy):
    """V polygons for a mark of `mark` units centred on (cx, cy), y down."""
    scale = mark * GLYPH_RATIO / UPEM
    mx, my = (X0 + X1) / 2, (Y0 + Y1) / 2
    return [[(cx + (x - mx) * scale, cy - (y - my) * scale) for x, y in c] for c in CONTOURS]


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(path.relative_to(ROOT))


def save(path, image):
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, optimize=True)
    print(path.relative_to(ROOT))


def vector_foreground():
    def fmt(n):
        return f"{n:.3f}".rstrip("0").rstrip(".")
    data = "".join(
        "M" + "L".join(f"{fmt(x)},{fmt(y)}" for x, y in c) + "Z"
        for c in place_v(VISIBLE_DP, CANVAS_DP / 2, CANVAS_DP / 2)
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
{GENERATED}
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{CANVAS_DP}dp" android:height="{CANVAS_DP}dp"
    android:viewportWidth="{CANVAS_DP}" android:viewportHeight="{CANVAS_DP}">
    <path android:fillColor="{WHITE}" android:pathData="{data}" />
</vector>
"""


ADAPTIVE = f"""<?xml version="1.0" encoding="utf-8"?>
{GENERATED}
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
"""

COLOR = f"""<?xml version="1.0" encoding="utf-8"?>
{GENERATED}
<resources>
    <color name="ic_launcher_background">{BLACK}</color>
</resources>
"""


def legacy_icon(px, disc):
    """Pre-API-26 icon: a black rounded square (or disc) inside a 2/48 inset, holding the white V."""
    canvas = px * OVERSAMPLE
    image = Image.new("RGBA", (canvas, canvas), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    inset = canvas * LEGACY_INSET_DP / LEGACY_DP
    mark = canvas - 2 * inset
    box = (inset, inset, canvas - inset, canvas - inset)
    if disc:
        draw.ellipse(box, fill=BLACK)
    else:
        draw.rounded_rectangle(box, radius=mark * CORNER, fill=BLACK)
    for polygon in place_v(mark, canvas / 2, canvas / 2):
        draw.polygon(polygon, fill=WHITE)
    return image.resize((px, px), Image.Resampling.LANCZOS)


def static_font(size):
    """bricolage.ttf instanced at its default axes (opsz 96, wdth 100) as a static font.

    The app font is variable; FreeType rasterises it a little differently from
    the static remote_bricolage_800.ttf that design's master is drawn with,
    although the outlines are the same. Instancing it first makes tv_banner.png
    byte-identical to design's tv-banner-320x180.png."""
    font = TTFont(FONT)
    if "fvar" in font:
        font = instancer.instantiateVariableFont(
            font, {axis.axisTag: axis.defaultValue for axis in font["fvar"].axes})
    data = BytesIO()
    font.save(data)
    data.seek(0)
    return ImageFont.truetype(data, size)


def banner():
    """320x180 xhdpi TV banner: the white "VIPTV" wordmark centred on black.

    Mirrors banner() in design's make_app_icon.py: the channel-poster wordmark
    (72 px at 210 px high, -0.04 em tracking) scaled to 180 px high, without the
    lockup's mark, because the wordmark's own V is the icon's V."""
    width, height = 320, 180
    text_size = 72 * height / 210 * OVERSAMPLE
    image = Image.new("RGB", (width * OVERSAMPLE, height * OVERSAMPLE), BLACK)
    draw = ImageDraw.Draw(image)
    font = static_font(round(text_size))
    tracking = -text_size * 0.04
    word = sum(font.getlength(c) for c in WORDMARK) + tracking * (len(WORDMARK) - 1)
    x = (image.width - word) / 2
    cy = image.height / 2
    _, top, _, bottom = font.getbbox(WORDMARK)
    y = cy - (top + bottom) / 2
    for char in WORDMARK:
        draw.text((x, y), char, font=font, fill=WHITE)
        x += font.getlength(char) + tracking
    return image.resize((width, height), Image.Resampling.LANCZOS)


def main():
    write(RES / "values/ic_launcher_background.xml", COLOR)
    write(RES / "drawable/ic_launcher_foreground.xml", vector_foreground())
    for name in ("ic_launcher", "ic_launcher_round"):
        write(RES / f"mipmap-anydpi-v26/{name}.xml", ADAPTIVE)
    for density, factor in DENSITIES.items():
        px = round(LEGACY_DP * factor)
        save(RES / f"mipmap-{density}/ic_launcher.png", legacy_icon(px, disc=False))
        save(RES / f"mipmap-{density}/ic_launcher_round.png", legacy_icon(px, disc=True))
    save(RES / "drawable-xhdpi/tv_banner.png", banner())


if __name__ == "__main__":
    main()
