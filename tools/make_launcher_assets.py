#!/usr/bin/env python3
"""Generate the Android launcher icon, its adaptive and monochrome layers, the TV
banner, the in-app V vector, the desktop window and launcher icons and the
web favicon and PWA install icons from design's branded V.

Design's `assets/brand/viptv-v.svg` is the master: one closed path in the ink box
195.506 x 167. Every output places that path, scaled uniformly and centred on the
ink box, at 0.4125 x the mark size tall. Nothing types a V glyph.

Provenance (design commits, master files, hashes) is recorded in
androidApp/src/main/LAUNCHER_ASSETS.md.

Requires Python 3.13.5, Pillow 13.0.0 and fontTools 4.67.0 (pinned so the PNG
bytes reproduce):
  python3 -m venv /tmp/viptv-icons && /tmp/viptv-icons/bin/pip install pillow==13.0.0 fonttools==4.67.0
  /tmp/viptv-icons/bin/python tools/make_launcher_assets.py
"""
import math
import re
from functools import lru_cache
from io import BytesIO
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "composeApp/src/commonMain/composeResources/font/bricolage.ttf"
RES = ROOT / "androidApp/src/main/res"
COMPOSE_DRAWABLE = ROOT / "composeApp/src/commonMain/composeResources/drawable"
DESKTOP_RESOURCES = ROOT / "composeApp/src/desktopMain/resources"
WEB_RESOURCES = ROOT / "composeApp/src/wasmJsMain/resources"

MASTER = ("M 0 0 L 40.219 0 L 95.04 100.559 L 119.172 139 L 101.784 99.519 "
          "L 155.489 0 L 195.506 0 L 106.396 162.265 "
          "A 9.131 9.131 0 0 1 90.416 162.313 Z")
MASTER_WIDTH, MASTER_HEIGHT = 195.506, 167

INK = 0.4125  # V ink height / mark size; the BrandMark ratio
ICON_BG = "#000000"  # icon and banner ground; design token color.bg-oled
MARK = "#FFFFFF"     # the V and the wordmark; design token color.fill.white
CORNER = 0.28        # legacy rounded-square corner radius / size
OVERSAMPLE = 8
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
LEGACY_DP, LEGACY_INSET_DP = 48, 2
CANVAS_DP, VISIBLE_DP = 108, 72
WORDMARK = "VIPTV"
BANNER_TEXT_RATIO = 72 / 210
BANNER_TRACKING_EM = -0.04
DESKTOP_ICON_PX = 1024
TILE_BG = "#F5C542"   # nav tile ground; Palette.accent
TILE_MARK = "#0B0B0C" # the V on the tile; Palette.background
FAVICON_CORNER = 0.3  # BrandMark's RoundedCornerShape ratio
FAVICON_SIZE = 100    # SVG units; design's brand-mark-tile.svg canvas
FAVICON_ICO_PX = 64   # ICO source px; Pillow downsamples to 16-64
APPLE_TOUCH_PX = 180  # iOS home-screen icon
PWA_192_PX = 192
PWA_512_PX = 512
GENERATED = "<!-- Generated by tools/make_launcher_assets.py; do not edit by hand. -->"


@lru_cache
def read_master():
    """The master's start point and segments, in its own units."""
    tokens = re.findall(r"[A-Za-z]|-?\d*\.?\d+", MASTER)
    segments, start, i = [], None, 0
    while i < len(tokens):
        command = tokens[i]
        i += 1
        if command == "M":
            start = (float(tokens[i]), float(tokens[i + 1]))
            i += 2
        elif command == "L":
            segments.append(("L", (float(tokens[i]), float(tokens[i + 1]))))
            i += 2
        elif command == "A":
            segments.append(("A", (float(tokens[i]), float(tokens[i + 1])), tokens[i + 2], tokens[i + 3],
                             tokens[i + 4], (float(tokens[i + 5]), float(tokens[i + 6]))))
            i += 7
        elif command != "Z":
            raise SystemExit(f"unexpected command {command} in the master path")
    return start, segments


def shape(ink, cx, cy):
    """The master path at `ink` tall, its ink box centred on (cx, cy)."""
    start, segments = read_master()
    scale = ink / MASTER_HEIGHT
    dx, dy = cx - MASTER_WIDTH * scale / 2, cy - MASTER_HEIGHT * scale / 2
    placed = []
    for segment in segments:
        if segment[0] == "L":
            placed.append(("L", (dx + segment[1][0] * scale, dy + segment[1][1] * scale)))
        else:
            _, (rx, ry), rotation, large, sweep, end = segment
            placed.append(("A", (rx * scale, ry * scale), rotation, large, sweep,
                           (dx + end[0] * scale, dy + end[1] * scale)))
    return (dx + start[0] * scale, dy + start[1] * scale), placed


def place(mark, cx, cy):
    """The master path with an ink height of INK x mark, centred on (cx, cy)."""
    return shape(INK * mark, cx, cy)


def path(start, segments):
    parts = [f"M {fmt(start[0])} {fmt(start[1])}"]
    for segment in segments:
        if segment[0] == "L":
            parts.append(f"L {fmt(segment[1][0])} {fmt(segment[1][1])}")
        else:
            _, (rx, ry), rotation, large, sweep, end = segment
            parts.append(f"A {fmt(rx)} {fmt(ry)} {rotation} {large} {sweep} {fmt(end[0])} {fmt(end[1])}")
    return " ".join(parts) + " Z"


def arc_points(first, segment, steps=64):
    """A circular arc as points; the master's tip arc has rx == ry."""
    _, (rx, ry), rotation, large, sweep, end = segment
    if rx != ry or rotation != "0":
        raise SystemExit("only circular arcs are supported")
    (x0, y0), (x1, y1) = first, end
    half = ((x0 - x1) / 2, (y0 - y1) / 2)
    length2 = half[0] ** 2 + half[1] ** 2
    if length2 > rx * rx:
        raise SystemExit("arc radius too small for its chord")
    factor = math.sqrt((rx * rx - length2) / length2) * (1 if large != sweep else -1)
    centre = (factor * half[1] + (x0 + x1) / 2, -factor * half[0] + (y0 + y1) / 2)
    start_angle = math.atan2(y0 - centre[1], x0 - centre[0])
    end_angle = math.atan2(y1 - centre[1], x1 - centre[0])
    delta = end_angle - start_angle
    if sweep == "1" and delta < 0:
        delta += 2 * math.pi
    if sweep == "0" and delta > 0:
        delta -= 2 * math.pi
    return [(centre[0] + rx * math.cos(start_angle + delta * t / steps),
             centre[1] + ry * math.sin(start_angle + delta * t / steps))
            for t in range(1, steps + 1)]


def outline(start, segments):
    points = [start]
    for segment in segments:
        if segment[0] == "L":
            points.append(segment[1])
        else:
            points.extend(arc_points(points[-1], segment))
    return points


def fmt(value):
    return f"{value:.3f}".rstrip("0").rstrip(".")


def vector(width, height, viewport_width, viewport_height, body):
    return f"""<?xml version="1.0" encoding="utf-8"?>
{GENERATED}
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{fmt(width)}dp" android:height="{fmt(height)}dp"
    android:viewportWidth="{viewport_width}" android:viewportHeight="{viewport_height}">
    <path android:fillColor="{body[0]}" android:pathData="{body[1]}" />
</vector>
"""


def layer(fill):
    """A 108dp adaptive-icon layer: the V sized for the 72dp visible area."""
    return vector(CANVAS_DP, CANVAS_DP, fmt(CANVAS_DP), fmt(CANVAS_DP),
                  (fill, path(*place(VISIBLE_DP, CANVAS_DP / 2, CANVAS_DP / 2))))


COMPOSE_V = vector(MASTER_WIDTH, MASTER_HEIGHT, fmt(MASTER_WIDTH), fmt(MASTER_HEIGHT),
                   (MARK, path(*read_master())))

ADAPTIVE = f"""<?xml version="1.0" encoding="utf-8"?>
{GENERATED}
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""

COLOR = f"""<?xml version="1.0" encoding="utf-8"?>
{GENERATED}
<resources>
    <color name="ic_launcher_background">{ICON_BG}</color>
</resources>
"""


def legacy_icon(px, disc):
    """Pre-API-26 icon: a black rounded square (or disc) inside a 2/48 inset, holding the white V."""
    canvas = px * OVERSAMPLE
    image = Image.new("RGBA", (canvas, canvas), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    inset = canvas * LEGACY_INSET_DP / LEGACY_DP
    mark = canvas - 2 * inset
    box = (inset, inset, canvas - inset, canvas - inset)
    if disc:
        draw.ellipse(box, fill=ICON_BG)
    else:
        draw.rounded_rectangle(box, radius=mark * CORNER, fill=ICON_BG)
    draw.polygon(outline(*place(mark, canvas / 2, canvas / 2)), fill=MARK)
    return image.resize((px, px), Image.Resampling.LANCZOS)


def static_font(size):
    """bricolage.ttf instanced at its default axes (opsz 96, wdth 100) as a static font.

    The app font is variable; FreeType rasterises it a little differently from
    the static remote_bricolage_800.ttf that design's master is drawn with,
    although the outlines are the same. Instancing it first makes tv_banner.png
    byte-identical to design's tv-banner-320x180.png."""
    font = TTFont(FONT)
    font = instancer.instantiateVariableFont(
        font, {axis.axisTag: axis.defaultValue for axis in font["fvar"].axes})
    data = BytesIO()
    font.save(data)
    data.seek(0)
    return ImageFont.truetype(data, size)


def banner():
    """320x180 xhdpi TV banner: the white "VIPTV" wordmark centred on black.

    Mirrors banner() in design's make_app_icon.py: "IPT" in Bricolage
    Grotesque ExtraBold and the master's V, both at the same cap height, tracked
    -0.04 em, at the channel-poster wordmark size (72 px at 210 px high) scaled
    to 180 px high."""
    width, height = 320, 180
    font = static_font(round(BANNER_TEXT_RATIO * height * OVERSAMPLE))
    cap_box = font.getbbox("V")
    cap = cap_box[3] - cap_box[1]
    tracking = BANNER_TRACKING_EM * font.size
    mark_width = MASTER_WIDTH * cap / MASTER_HEIGHT

    items, pen = [], 0.0
    for char in WORDMARK:
        if char == "V":
            items.append({"mark": True, "pen": pen, "width": mark_width})
            pen += mark_width + tracking
        else:
            items.append({"mark": False, "pen": pen, "char": char, "box": font.getbbox(char)})
            pen += font.getlength(char) + tracking

    def ink(item):
        if item["mark"]:
            return item["pen"], item["pen"] + item["width"]
        return item["pen"] + item["box"][0], item["pen"] + item["box"][2]

    left = min(ink(item)[0] for item in items)
    right = max(ink(item)[1] for item in items)
    image = Image.new("RGB", (width * OVERSAMPLE, height * OVERSAMPLE), ICON_BG)
    draw = ImageDraw.Draw(image)
    shift = (image.width - (right - left)) / 2 - left
    middle = image.height / 2
    text_y = middle - (cap_box[1] + cap_box[3]) / 2
    for item in items:
        if item["mark"]:
            draw.polygon(outline(*shape(cap, item["pen"] + shift + mark_width / 2, middle)), fill=MARK)
        else:
            draw.text((item["pen"] + shift, text_y), item["char"], font=font, fill=MARK)
    return image.resize((width, height), Image.Resampling.LANCZOS)


def square_icon(px):
    scale = px * OVERSAMPLE
    image = Image.new("RGB", (scale, scale), ICON_BG)
    ImageDraw.Draw(image).polygon(
        [(x * OVERSAMPLE, y * OVERSAMPLE) for x, y in outline(*place(px, px / 2, px / 2))], fill=MARK)
    return image.resize((px, px), Image.Resampling.LANCZOS)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(path.relative_to(ROOT))


def save(path, image):
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, optimize=True)
    print(path.relative_to(ROOT))


def desktop_icons():
    """The desktop window icon and the three jpackage launcher icons.

    The square is design's `app-icon-square-1024.png` (white V on black,
    1024 px). jpackage wants a PNG for Linux, an ICO for Windows and an ICNS
    for macOS, so Pillow downsizes the same square into the ICO (16-256 px)
    and ICNS (16-1024 px) containers; the PNG serves both the window and the
    Linux launcher."""
    square = square_icon(DESKTOP_ICON_PX)
    save(DESKTOP_RESOURCES / "viptv-app-icon.png", square)
    for name, fmt in (("viptv-app-icon.ico", "ICO"), ("viptv-app-icon.icns", "ICNS")):
        path = DESKTOP_RESOURCES / name
        square.save(path, format=fmt)
        print(path.relative_to(ROOT))


def tile(px, corner):
    """The nav tile at `px`: TILE_BG ground, the dark V, corners rounded `corner` of the size.

    `corner` 0 fills the square edge to edge for hosts that round it themselves."""
    canvas = px * OVERSAMPLE
    image = Image.new("RGBA", (canvas, canvas), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    if corner:
        draw.rounded_rectangle((0, 0, canvas, canvas), radius=canvas * corner, fill=TILE_BG)
    else:
        draw.rectangle((0, 0, canvas, canvas), fill=TILE_BG)
    draw.polygon(
        [(x * OVERSAMPLE, y * OVERSAMPLE) for x, y in outline(*place(px, px / 2, px / 2))],
        fill=TILE_MARK)
    return image.resize((px, px), Image.Resampling.LANCZOS)


def favicon():
    """The browser tab favicon and the PWA install icons, all the nav tile.

    The SVG and the 192 px install icon keep the tile's rounded corners; the ICO,
    the touch icon and the 512 px install icon fill the square edge to edge,
    because browsers, iOS and icon masks round the corners themselves. The 512 px
    icon is the maskable glyph, and its V sits inside the maskable safe zone."""
    write(WEB_RESOURCES / "favicon.svg", f"""<?xml version="1.0" encoding="utf-8"?>
{GENERATED}
<svg xmlns="http://www.w3.org/2000/svg" width="{FAVICON_SIZE}" height="{FAVICON_SIZE}" viewBox="0 0 {FAVICON_SIZE} {FAVICON_SIZE}">
    <rect width="{FAVICON_SIZE}" height="{FAVICON_SIZE}" rx="{FAVICON_CORNER * FAVICON_SIZE}" fill="{TILE_BG}"/>
    <path fill="{TILE_MARK}" d="{path(*place(FAVICON_SIZE, FAVICON_SIZE / 2, FAVICON_SIZE / 2))}"/>
</svg>
""")
    for name, px, corner in (
        ("favicon.ico", FAVICON_ICO_PX, FAVICON_CORNER),
        ("icon-192.png", PWA_192_PX, FAVICON_CORNER),
        ("apple-touch-icon.png", APPLE_TOUCH_PX, 0),
        ("icon-512.png", PWA_512_PX, 0),
    ):
        image = tile(px, corner)
        if name.endswith(".ico"):
            target = WEB_RESOURCES / name
            image.save(target, format="ICO")
            print(target.relative_to(ROOT))
        else:
            save(WEB_RESOURCES / name, image)


def main():
    write(RES / "values/ic_launcher_background.xml", COLOR)
    write(RES / "drawable/ic_launcher_foreground.xml", layer(MARK))
    write(RES / "drawable/ic_launcher_monochrome.xml", layer(ICON_BG))
    for name in ("ic_launcher", "ic_launcher_round"):
        write(RES / f"mipmap-anydpi-v26/{name}.xml", ADAPTIVE)
    for density, factor in DENSITIES.items():
        px = round(LEGACY_DP * factor)
        save(RES / f"mipmap-{density}/ic_launcher.png", legacy_icon(px, disc=False))
        save(RES / f"mipmap-{density}/ic_launcher_round.png", legacy_icon(px, disc=True))
    save(RES / "drawable-xhdpi/tv_banner.png", banner())
    write(COMPOSE_DRAWABLE / "viptv_v.xml", COMPOSE_V)
    desktop_icons()
    favicon()


if __name__ == "__main__":
    main()